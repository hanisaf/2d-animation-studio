// Rebuild the portable, offline game from the shared rigs and editable game sources.
import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('../games/robo-invaders/', import.meta.url);
let html = await readFile(new URL('page.html', base), 'utf8');
const sources = [...html.matchAll(/<script(?: type="module")? src="([^"]+)"><\/script>/g)];
const scripts = [];
for (const [, path] of sources) {
  let source = await readFile(new URL(path, base), 'utf8');
  if (path === 'game.js') {
    const model = (await readFile(new URL('model.js', base), 'utf8')).replace(/^export /gm, '');
    source = source.replace(/^import[^;]+;\s*/, '');
    source = `(() => {\n${model}\n${source}\n})();`;
  }
  scripts.push(`// Source: ${path}\n${source}`);
}
html = html.replace(/<script(?: type="module")? src="[^"]+"><\/script>\s*/g, '');
const code = scripts.join('\n').replace(/[ \t]+$/gm, '');
html = html.replace('</body>', '<script src="runtime.js"></script>\n</body>');
await writeFile(new URL('runtime.js', base), `// Generated by npm run build:game.\n(() => {\n${code}\n})();\n`);
html = '<!-- Generated by npm run build:game. Edit page.html, style.css, model.js or game.js, then rebuild. -->\n' + html;
await writeFile(new URL('index.html', base), html);
console.log('Built games/robo-invaders/index.html + style.css + runtime.js — standalone, offline, no server required.');
