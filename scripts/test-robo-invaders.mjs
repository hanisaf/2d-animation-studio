import assert from 'node:assert/strict';
import { Game } from '../games/robo-invaders/model.js';
const game = new Game(() => .5);
assert.equal(game.state, 'ready');
game.reset();
assert.equal(game.invaders.length, 24);
for (let i = 0; i < 120; i++) game.update(1 / 120, { left: true });
assert.equal(Math.round(game.player.x), 120);
for (let i = 0; i < 120; i++) game.update(1 / 120, { left: true });
assert.equal(game.player.x, 44);
game.reset();
const target = game.invaders[0];
game.bolts.push({ x: target.x, y: target.y - 15 });
game.update(1 / 120);
assert.equal(game.invaders.length, 23); assert.equal(game.score, 30); assert.equal(game.bolts.length, 0);
game.invaders = []; game.drops = [{ x: 500, y: 100, speed: 1 }];
for (let i = 0; i < 240; i++) game.update(1 / 120);
assert.equal(game.wave, 2); assert.equal(game.invaders.length, 24); assert.equal(game.drops.length, 0);
game.player.immune = 0;
game.drops.push({ x: game.player.x, y: 560, speed: 1 }); game.update(1 / 120);
assert.equal(game.lives, 2); game.hurt(); assert.equal(game.lives, 2);
game.player.immune = 0; game.hurt(); game.player.immune = 0; game.hurt();
assert.equal(game.state, 'over'); assert.equal(game.lives, 0);
game.reset(); game.invaders[0].y = 514; game.update(1 / 120); assert.equal(game.state, 'over');
game.reset(); game.state = 'paused'; const snapshot = JSON.stringify(game); game.update(1); assert.equal(JSON.stringify(game), snapshot);
game.reset(); game.invaders.forEach(e => e.x += 200); game.update(1 / 120);
assert.equal(game.direction, -1); assert.equal(game.invaders[0].y, 142);
game.reset(); game.update(1 / 120, { fire: true }); assert.equal(game.bolts.length, 1);
game.update(1 / 120, { fire: true }); assert.equal(game.bolts.length, 1);
console.log('Robo Invaders: movement, collision, scoring, waves, lives, invulnerability, defeat, pause, formation, and fire cooldown passed.');
