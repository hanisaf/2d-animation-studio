// Package the original rigs so the arcade remains portable within games/.
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const sources = await Promise.all(['engine/core.js', 'characters/sami/sami.js', 'characters/safadi/safadi.js'].map(path => readFile(new URL(path, root), 'utf8')));
// Give this page a smooth, alternating eyebrow pose without changing shared rigs.
const rigs = sources.map(source => source.replaceAll('const y = -1.05 - up,', 'up += (o.browShift || 0) * (i ? 1 : -1);\n    const y = -1.05 - up,'));
const animation = await readFile(new URL('games/hosts.js', root), 'utf8');
await writeFile(new URL('games/assets/hosts-runtime.js', root), '// Generated by node scripts/build-arcade-hosts.mjs\n(() => {\nconst CHARACTERS = {};\n' + rigs.join('\n') + '\n' + animation + '\n})();\n');
