import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url), base=new URL('games/family-fighter/',root);
const ids='jester_fester princess_pearl safadi alma dragon housam danny sami jenna robo_safadi clawd neptune sarah'.split(' ');
let code='';
for(const file of ['engine/core.js','engine/timeline.js'])code+=await readFile(new URL(file,root),'utf8')+'\n';
for(const id of ids){
 const dir=new URL(`characters/${id}/`,root),manifest=await readFile(new URL('asset.js',dir),'utf8');
 const files=manifest.match(/files:\s*\[([^\]]+)\]/)[1].matchAll(/'([^']+)'/g);
 code+=`\nCURRENT_ASSET={id:'${id}',kind:'character',dir:'characters/${id}'};\n`+manifest+'\n';
 for(const [,file]of files)code+=await readFile(new URL(file,dir),'utf8')+'\n';
}
const arenas=(await readFile(new URL('arenas.js',base),'utf8')).replace(/^export /gm,'');
const model=(await readFile(new URL('model.js',base),'utf8')).replace(/^export /gm,'');
const game=(await readFile(new URL('game.js',base),'utf8')).replace(/^import[^;]+;\s*/gm,'');
await writeFile(new URL('runtime.js',base),'// Generated by npm run build:family-fighter\n(()=>{\n'+code+'\n(()=>{\n'+arenas+'\n'+model+'\n'+game+'\n})();\n})();\n');
await writeFile(new URL('index.html',base),'<!-- Generated: edit page.html, then npm run build:family-fighter -->\n'+await readFile(new URL('page.html',base),'utf8'));
console.log('Built offline Family Fighter.');
